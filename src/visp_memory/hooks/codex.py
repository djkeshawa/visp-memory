"""
Codex Adapter

Integrates visp-memory with Codex by:
1. Adding project-level AGENTS.md workflow instructions.
2. Installing a marked MCP server block in the Codex config.
"""

from pathlib import Path
from typing import Dict

from visp_memory.core.instruction_markers import CODEX_CONTEXT_MARKER
from visp_memory.core.verbs import (
    CAPTURE_VERBS,
    INTENT_NON_AUTHORITATIVE_NOTE,
    INTENT_VERBS,
    render_inline_commands,
    render_inline_mcp_tools,
)
from visp_memory.hooks.base import _replace_between_markers
from visp_memory.hooks.generic import GenericAdapter

CODEX_MARKER = "LLM-MEMORY CODEX MCP"
AGENTS_MARKER = CODEX_CONTEXT_MARKER


class CodexAdapter(GenericAdapter):
    """Adapter for Codex memory workflow integration."""

    def __init__(
        self,
        memory,
        project_root: Path = None,
        config_path: Path = None,
        server_url: str = "http://127.0.0.1:8000",
        repo_id: str = None,
        dry_run: bool = False,
    ):
        super().__init__(
            memory=memory,
            project_root=project_root,
            context_file="AGENTS.md",
            injection_marker=AGENTS_MARKER,
            append_mode=True,
            dry_run=dry_run,
        )
        self.config_path = Path(config_path or Path.home() / ".codex" / "config.toml")
        self.server_url = server_url
        self.repo_id = repo_id or getattr(memory.config, "repo_id", None) or self.project_root.name

    def install(self) -> Dict[str, bool]:
        """Install project instructions and a Codex MCP config block."""
        results = {}
        results["agents_instructions"] = self._install_agents_instructions()
        results["codex_mcp_config"] = self._install_codex_config()
        return results

    def uninstall(self) -> Dict[str, bool]:
        """Remove only visp-memory managed Codex integration blocks."""
        results = {}
        results["agents_instructions"] = self._remove_agents_instructions()
        results["codex_mcp_config"] = self._remove_codex_config()
        return results

    def update_context(self, files: list[str] = None, task: str = None) -> bool:
        """Refresh the generated memory context inside AGENTS.md."""
        if self.dry_run:
            return True
        if not self.context_file.exists():
            self.install()

        context = self.get_memory_context(files=files, task=task)
        generated = f"""{self._workflow_instructions()}

## Visp Memory Context

Auto-generated by `visp-memory hooks update codex`.

{context}
"""
        return self._replace_agents_block(generated)

    def get_context_file_path(self) -> Path:
        """Get the Codex project instruction path."""
        return self.context_file

    def config_block(self) -> str:
        """Render the managed Codex MCP config block."""
        env_items = {
            "VISP_MEMORY_STORAGE_MODE": "client",
            "VISP_MEMORY_STORAGE_SERVER_URL": self.server_url,
            "VISP_MEMORY_REPO_ID": self.repo_id,
        }
        env = ", ".join(
            f'{key} = "{self._toml_string(value)}"' for key, value in env_items.items()
        )
        return (
            f"# BEGIN {CODEX_MARKER}\n"
            "[mcp_servers.visp-memory]\n"
            'command = "visp-memory-mcp"\n'
            "args = []\n"
            f'cwd = "{self._toml_string(self.project_root)}"\n'
            f"env = {{ {env} }}\n"
            f"# END {CODEX_MARKER}\n"
        )

    def _install_agents_instructions(self) -> bool:
        instructions = f"""# AGENTS.md

{AGENTS_MARKER} START

{self._workflow_instructions()}

## Visp Memory Context

Run `visp-memory hooks update codex` to populate current memory context.

{AGENTS_MARKER} END
"""
        exists = self.context_file.exists()
        content = self.context_file.read_text(encoding="utf-8") if exists else ""
        if AGENTS_MARKER in content:
            return self._valid_markers(content)
        if self.dry_run:
            return True

        if not exists:
            self._ensure_directory(self.context_file)
            self.context_file.write_text(instructions, encoding="utf-8")
            return True

        # About to modify an existing user file - back it up first.
        self._backup_file(self.context_file)
        with self.context_file.open("a", encoding="utf-8") as f:
            f.write("\n\n" + instructions.replace("# AGENTS.md\n\n", ""))
        return True

    def _workflow_instructions(self) -> str:
        """Render the managed AGENTS.md workflow block.

        The verb names come from the one catalogue in ``core.verbs`` rather than
        being spelled out here: this block used to say "follow-up goals" in prose
        while naming only the capture verbs, so the intent lifecycle was
        unreachable from the instructions an assistant actually reads.
        """
        intent_cli = render_inline_commands(INTENT_VERBS)
        intent_mcp = render_inline_mcp_tools(INTENT_VERBS)
        capture_cli = render_inline_commands(CAPTURE_VERBS)
        return f"""## Codex Memory Workflow

Use visp-memory as the persistent project memory for this repository.

- Before changing code, run `visp-memory remember --repo {self.repo_id}` or call
  MCP `memory_remember`, then run `visp-memory recall "<task>" --repo {self.repo_id}`
  or call MCP `memory_recall`.
- Set the direction before you start and keep it current with {intent_cli}
  (MCP {intent_mcp}); `visp-memory intent list|update|complete|close` revises
  what is already there.
- For file-specific risk, call MCP `memory_file_context` or run
  `visp-memory inject --file <path> --task "<task>"`.
- After meaningful work, record bug fixes, decisions, conventions and fragile
  areas with {capture_cli}, or MCP `memory_after_work`.
- Keep memory scoped to repo `{self.repo_id}` unless intentionally recording
  cross-project knowledge.
- Do not print secrets, prompts, responses, API keys, or unrelated repo/team memory.

{INTENT_NON_AUTHORITATIVE_NOTE}
"""

    def _install_codex_config(self) -> bool:
        block = self.config_block()
        content = self.config_path.read_text(encoding="utf-8") if self.config_path.exists() else ""
        new_content = self._replace_marked_block(content, block)
        if new_content is None:
            return False
        if self.dry_run:
            return True

        self._ensure_directory(self.config_path)
        # Back up an existing config before the destructive rewrite.
        self._backup_file(self.config_path)
        self.config_path.write_text(new_content, encoding="utf-8")
        return True

    def _remove_agents_instructions(self) -> bool:
        if self.dry_run or not self.context_file.exists():
            return True

        content = self.context_file.read_text(encoding="utf-8")
        new_content = self._remove_marked_section(
            content, f"{AGENTS_MARKER} START", f"{AGENTS_MARKER} END"
        )
        if new_content == content:
            return True

        # Back up before the destructive rewrite.
        self._backup_file(self.context_file)
        self.context_file.write_text(new_content.strip() + "\n", encoding="utf-8")
        return True

    def _remove_codex_config(self) -> bool:
        if self.dry_run or not self.config_path.exists():
            return True

        content = self.config_path.read_text(encoding="utf-8")
        new_content = self._remove_marked_section(
            content, f"# BEGIN {CODEX_MARKER}", f"# END {CODEX_MARKER}"
        )
        if new_content == content:
            return True

        # Back up before the destructive rewrite.
        self._backup_file(self.config_path)
        self.config_path.write_text(
            new_content.strip() + ("\n" if new_content.strip() else ""), encoding="utf-8"
        )
        return True

    def _replace_agents_block(self, generated: str) -> bool:
        if self.dry_run:
            return True

        content = self.context_file.read_text(encoding="utf-8")
        start_marker = f"{AGENTS_MARKER} START"
        end_marker = f"{AGENTS_MARKER} END"

        # Only rewrite when the markers are well-formed (present once each,
        # start before end). Malformed/duplicated/reordered markers => refuse.
        new_content = _replace_between_markers(
            content, start_marker, end_marker, f"\n\n{generated}\n"
        )
        if new_content is None:
            return False

        self.context_file.write_text(new_content, encoding="utf-8")
        return True

    def _replace_marked_block(self, content: str, block: str) -> str | None:
        begin = f"# BEGIN {CODEX_MARKER}"
        end = f"# END {CODEX_MARKER}"

        # If a managed block is present, replace it only when the markers are
        # well-formed (each present once, start before end). The replacement
        # collapses the region and drops the old marker strings, since `block`
        # carries its own BEGIN/END lines.
        if begin in content or end in content:
            collapsed = _replace_between_markers(content, begin, end, "")
            if collapsed is None:
                # Malformed/duplicated/reordered managed markers - refuse.
                return None
            before, after = collapsed.split(begin + end, 1)
            return f"{before}{block}{after.lstrip()}"

        unmanaged_table = "[mcp_servers.visp-memory]" in content
        if unmanaged_table:
            return None

        separator = "" if not content or content.endswith("\n") else "\n"
        return f"{content}{separator}\n{block}" if content else block

    def _remove_marked_section(self, content: str, begin: str, end: str) -> str:
        if begin not in content or end not in content:
            return content

        before = content.split(begin)[0]
        after = content.split(end, 1)[1]
        return before + after

    def _toml_string(self, value: object) -> str:
        return str(value).replace("\\", "\\\\").replace('"', '\\"')
